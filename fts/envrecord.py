"""Record exact library versions and licenses (Req 0.5, 0.6, 0.7, 1.6).

Writes the "Python environment" section of docs/ENVIRONMENT.md, whose verifiable
artifact is the package manager's own query (``uv pip show``) for the exact
installed versions plus a CUDA check from torch, and the "Python packages" and
"Base model" sections of THIRD_PARTY.md, built from each installed
distribution's license metadata and config/model.yaml.
"""

from __future__ import annotations

import re
import subprocess
import tomllib
from collections.abc import Callable, Iterable
from importlib import metadata
from pathlib import Path

from fts import envdoc, repro, settings

REPO_ROOT = Path(__file__).resolve().parent.parent
THIRD_PARTY_MD = REPO_ROOT / "THIRD_PARTY.md"
UV_LOCK = REPO_ROOT / "uv.lock"
PYPROJECT = REPO_ROOT / "pyproject.toml"
KEY_PACKAGES = ("torch", "transformers", "peft", "accelerate", "huggingface-hub", "safetensors", "tokenizers")

_LICENSE_CLASSIFIER = re.compile(r"^License :: (?:OSI Approved :: )?(.+)$")


def direct_dependencies(pyproject: Path = PYPROJECT) -> list[tuple[str, str]]:
    """(name, pinned version) for every dependency in pyproject.toml."""
    deps = tomllib.loads(pyproject.read_text(encoding="utf-8"))["project"]["dependencies"]
    out = []
    for dep in deps:
        name, _, version = dep.partition("==")
        out.append((name.strip(), version.strip()))
    return out


def locked_packages(lock: Path = UV_LOCK) -> list[tuple[str, str]]:
    """(name, version) of every package in uv.lock except the project itself."""
    data = tomllib.loads(lock.read_text(encoding="utf-8"))
    # A package can appear once per Python-version marker; list each name once.
    seen: dict[str, str] = {}
    for p in data.get("package", []):
        if p.get("source", {}).get("editable") is None:
            seen.setdefault(p["name"], p["version"])
    return sorted(seen.items())


def license_of(dist: metadata.Distribution) -> str:
    """The SPDX expression if declared, else the License field's first line, else license classifiers."""
    meta = dist.metadata
    expr = meta.get("License-Expression")
    if expr:
        return expr.strip()
    lic = (meta.get("License") or "").strip()
    if lic and lic.upper() != "UNKNOWN" and "\n" not in lic and len(lic) <= 60:
        return lic
    classifiers = [m.group(1) for c in meta.get_all("Classifier") or [] if (m := _LICENSE_CLASSIFIER.match(c))]
    if classifiers:
        return "; ".join(classifiers)
    if lic:
        return lic.splitlines()[0][:60]
    return "not declared in package metadata"


def license_rows(packages: Iterable[tuple[str, str]], lookup: Callable[[str], metadata.Distribution] = metadata.distribution) -> list[tuple[str, str, str]]:
    rows = []
    for name, version in packages:
        try:
            dist = lookup(name)
        except metadata.PackageNotFoundError:
            rows.append((name, version, "not installed in this environment"))
            continue
        rows.append((name, dist.version, license_of(dist)))
    return rows


def render_license_table(rows: list[tuple[str, str, str]], direct: set[str]) -> str:
    lines = [
        "Generated by `python scripts/record_env.py` from each installed distribution's license metadata "
        "(`License-Expression`, `License`, or license classifiers). Direct dependencies are in bold.",
        "",
        "| Package | Version | License |",
        "| --- | --- | --- |",
    ]
    for name, version, lic in rows:
        shown = f"**{name}**" if name in direct else name
        lines.append(f"| {shown} | {version} | {lic.replace('|', '/')} |")
    return "\n".join(lines)


def render_base_model(model: settings.ModelSettings) -> str:
    return "\n".join(
        [
            "| Name | Version (Hugging Face revision) | License | Source |",
            "| --- | --- | --- | --- |",
            f"| {model.name} | {model.revision} | {model.license} | https://huggingface.co/{model.name} |",
            "",
            "The weights are downloaded to the Hugging Face cache at run time and never committed. "
            "The fine-tuned weights and Adapters are not published.",
        ]
    )


def uv_pip_show(names: Iterable[str], runner: Callable[[list[str]], str] | None = None) -> str:
    """Output of ``uv pip show <names>`` (the package manager's query of the installed versions)."""
    import sys

    cmd = ["uv", "pip", "show", "--python", sys.executable, *names]
    if runner is not None:
        return runner(cmd)
    out = subprocess.run(cmd, capture_output=True, text=True, check=True)
    return out.stdout


def torch_info() -> dict:
    import torch

    info = {
        "torch": torch.__version__,
        "cuda_runtime": torch.version.cuda,
        "cudnn": torch.backends.cudnn.version(),
        "cuda_available": torch.cuda.is_available(),
    }
    if info["cuda_available"]:
        info["device"] = torch.cuda.get_device_name(0)
    return info


def render_environment(versions: list[tuple[str, str, str]], pip_show: str, tinfo: dict, uv_version: str, python_version: str, stamp: repro.Stamp) -> str:
    lines = [
        f"- Python: `{python_version}`; uv: `{uv_version}`; environment `~/.venvs/fts` created by `uv sync --frozen` from `uv.lock`",
        f"- torch `{tinfo['torch']}` built for CUDA `{tinfo['cuda_runtime']}`, cuDNN `{tinfo['cudnn']}`; "
        f"`torch.cuda.is_available()` = `{tinfo['cuda_available']}`" + (f" on `{tinfo['device']}`" if tinfo.get("device") else ""),
        *envdoc.stamp_lines(stamp),
        "",
        "| Package | Installed version | License |",
        "| --- | --- | --- |",
        *[f"| {n} | {v} | {lic} |" for n, v, lic in versions],
        "",
        "Verifiable artifact: `uv pip show` on this machine for the fine-tuning stack:",
        "",
        *envdoc.code_block(pip_show),
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None, env_md: Path = envdoc.ENVIRONMENT_MD, third_party_md: Path = THIRD_PARTY_MD) -> int:
    import platform

    stamp = repro.start_run(seed=0)
    direct = direct_dependencies()
    key_rows = license_rows([(n, "") for n in KEY_PACKAGES])
    pip_show = uv_pip_show(KEY_PACKAGES)
    uv_version = subprocess.run(["uv", "--version"], capture_output=True, text=True, check=True).stdout.strip()
    envdoc.replace_section(
        "Python environment",
        render_environment(key_rows, pip_show, torch_info(), uv_version, platform.python_version(), stamp),
        env_md,
    )
    rows = license_rows(locked_packages())
    envdoc.replace_section("Python packages", render_license_table(rows, {n for n, _ in direct}), third_party_md)
    envdoc.replace_section("Base model", render_base_model(settings.load_model_settings()), third_party_md)
    print(f"recorded {len(key_rows)} key packages in {env_md} and {len(rows)} package licenses in {third_party_md}")
    return 0
